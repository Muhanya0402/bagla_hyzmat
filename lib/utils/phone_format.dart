/// Приведение телефона к единому виду для ОТОБРАЖЕНИЯ.
///
/// Зачем: номера попадают в базу из разных мест и в разном формате —
/// телефон клиента вводится в приложении через маску и сохраняется как
/// «+993 65 71 11 28», а телефон магазина приходит из регистрации как
/// «+99361553303». В карточке заказа они стояли рядом и выглядели
/// по-разному. Эта функция убирает разделители и даёт компактный вид.
///
/// ```
/// '+993 65 71 11 28' -> '+99365711128'
/// '+99361553303'     -> '+99361553303'
/// '993 61 55 33 03'  -> '+99361553303'
/// ```
///
/// Пустую строку и мусор возвращает как есть — форматирование не должно
/// «съедать» данные, которые оно не поняло.
String formatPhoneCompact(String raw) {
  final value = raw.trim();
  if (value.isEmpty) return value;

  final cleaned = value.replaceAll(RegExp(r'[^\d+]'), '');
  final digits = cleaned.replaceAll('+', '');
  if (digits.isEmpty) return value;

  // «+» сохраняем, если он был. Если его нет, но номер начинается с кода
  // страны 993 — добавляем, чтобы вид был единым для всех записей.
  final needsPlus = cleaned.startsWith('+') || digits.startsWith('993');
  return needsPlus ? '+$digits' : digits;
}
